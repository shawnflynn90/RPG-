export const FONT_KEY = 'pixel';
export const FONT_SIZE = 9;
export const LINE_HEIGHT = 10;

/** Build the bitmap font texture + data and register it with Phaser. */
export function createPixelFont(scene) {
  if (scene.cache.bitmapFont.exists(FONT_KEY)) return;
  const entries = Object.entries(G).map(([ch, [top, ...rows]]) => ({
    ch,
    top,
    rows,
    w: Math.max(...rows.map((r) => r.length)),
  }));
  const texW = entries.reduce((s, e) => s + e.w + 1, 0);
  const texH = FONT_SIZE;
  const tex = scene.textures.createCanvas(FONT_KEY + '_tex', texW, texH);
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  const chars = {};
  let x = 0;
  for (const e of entries) {
    e.rows.forEach((row, ry) => {
      [...row].forEach((c, rx) => {
        if (c === '#') ctx.fillRect(x + rx, e.top + ry, 1, 1);
      });
    });
    const code = e.ch.charCodeAt(0);
    const advance = e.ch === ' ' ? 3 : e.w + 1;
    chars[code] = {
      x,
      y: 0,
      width: e.w,
      height: texH,
      centerX: Math.floor(e.w / 2),
      centerY: Math.floor(texH / 2),
      xOffset: 0,
      yOffset: 0,
      xAdvance: advance,
      data: {},
      kerning: {},
      u0: x / texW,
      v0: 0,
      u1: (x + e.w) / texW,
      v1: 1,
    };
    x += e.w + 1;
  }
  tex.refresh();
  scene.cache.bitmapFont.add(FONT_KEY, {
    data: { font: FONT_KEY, size: FONT_SIZE, lineHeight: LINE_HEIGHT, chars },
    texture: FONT_KEY + '_tex',
    frame: null,
  });
}

/** Draw text straight onto a 2D canvas (used for placeholder icons). Returns the width drawn. */
export function drawGlyphs(ctx, str, x, y, color = '#ffffff') {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of str) {
    const g = G[ch] || G['?'];
    const [top, ...rows] = g;
    rows.forEach((row, ry) => [...row].forEach((c, rx) => c === '#' && ctx.fillRect(cx + rx, y + top + ry, 1, 1)));
    cx += ch === ' ' ? 3 : Math.max(...rows.map((r) => r.length)) + 1;
  }
  return cx - x - 1;
}

/** Width in pixels of a string in the pixel font. */
export function measureText(str) {
  let w = 0;
  for (const ch of str) {
    const g = G[ch] || G['?'];
    w += ch === ' ' ? 3 : Math.max(...g.slice(1).map((r) => r.length)) + 1;
  }
  return Math.max(0, w - 1);
}

/** Convenience: crisp pixel text. Origin top-left. */
export function pixelText(scene, x, y, str, color = 0xffffff) {
  const t = scene.add.bitmapText(x, y, FONT_KEY, str); // native size of whichever font is loaded
  t.setTint(color);
  return t;
}

/** Word-wrap a string (respecting \n) to lines no wider than maxWidth pixels. */
export function wrapText(str, maxWidth) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? line + ' ' + word : word;
      if (measureText(test) <= maxWidth || !line) line = test;
      else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}
